/** Private preview only: exact public markup, substituting the three server reads
 * with their context hooks. Fail rather than silently drift when sources change. */
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
for(const [file,name] of [['app/page.tsx','Home'],['app/story/page.tsx','Story'],['app/contact/page.tsx','Contact'],['components/PrintProductPage.tsx','Print']]){
 const source=await readFile(path.join(root,file),'utf8');
 let code=source.replace(/import \{readContentAdapter\} from "@\/lib\/content\/server-adapter";/,'import {useContentAdapter} from "@/components/content/useContentAdapter";')
  .replaceAll('"next-intl/server"','"next-intl"').replaceAll('readContentAdapter','useContentAdapter').replaceAll('getTranslations','useTranslations').replaceAll('getLocale','useLocale')
  .replace('export default async function','export default function').replace(/await (useContentAdapter|useTranslations|useLocale)\(/g,'$1(')
  .replace(/import "\.\/([^"\n]+\.css)";/g,(_,css)=>`import "@/${path.posix.dirname(file)}/${css}";`);
 if(code.includes('server-adapter')||code.includes('await '))throw Error(`Review private preview transform for ${file}`);
 code=`'use client';\n// Generated by scripts/generate-visual-preview.mjs from ${file}. Do not edit.\n${code}`;
 const target=path.join(root,`components/content/visual/generated/${name}.tsx`);
 if(process.argv.includes('--check')){
  if(await readFile(target,'utf8').catch(()=>null)!==code)throw Error(`Stale visual preview: run node scripts/generate-visual-preview.mjs (${name})`);
 }else{await mkdir(path.dirname(target),{recursive:true});await writeFile(target,code);}
}
console.log('Private visual preview renderers match public source.');
