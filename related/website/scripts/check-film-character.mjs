import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const browser = await chromium.launch({channel:'chrome',headless:true});
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 await page.goto('http://127.0.0.1:4211/en');
 await page.waitForTimeout(8000);
 const clip=page.locator('.lh-film-character');
 await page.locator('.lh-films-section').scrollIntoViewIfNeeded();
 await page.waitForFunction(()=>document.querySelector('.lh-film-character').currentTime>0.5);
 assert.equal(await clip.evaluate(v=>getComputedStyle(v).pointerEvents),'none');
 assert.equal(await clip.evaluate(v=>v.muted),true);
 assert.ok((await clip.evaluate(v=>v.currentSrc)).includes('ola-girl-v2-alpha.webm'));
 for (const width of [2279,1920,1440]) {
  await page.setViewportSize({width,height:1000});
  await page.waitForTimeout(900);
  const girl=await clip.boundingBox();
  const edge=await page.locator('.lh-film-card').boundingBox();
  assert.ok(girl.height >= Math.min(width*.34,760)-2,'character retains afternoon height');
  assert.ok(edge.width/width < .49,'video keeps afternoon viewport proportion');
  assert.ok(Math.abs(girl.x+girl.width*.89-edge.x)<8,'extended fingertip meets card left edge');
  assert.ok(girl.x+girl.width*.78<edge.x,'body stays left of card');
 }
 const ratio=await page.evaluate(()=>document.querySelector('.lh-film-card').getBoundingClientRect().width/document.querySelector('.lh-films-stage').getBoundingClientRect().width);
 assert.ok(Math.abs(ratio-.91)<.01,'selected film must be 30% larger than its previous 70% width');
 const top=await page.locator('.lh-film-preview-top').last().boundingBox();
 const bottom=await page.locator('.lh-film-preview-bottom').first().boundingBox();
 assert.ok(top.y<bottom.y,'previews are stacked vertically');
 const controls=await page.locator('.lh-films-controls').boundingBox();
 const card=await page.locator('.lh-film-card').boundingBox();
 assert.ok(controls.x>card.x+card.width,'controls sit to the right');
 assert.ok(Math.abs(controls.height-card.height)<3,'controls match card height');
 await page.locator('.lh-film-card').hover();
 await page.mouse.wheel(0,120);
 await page.waitForTimeout(300);
 const during=await page.locator('.lh-film-card').boundingBox();
 assert.ok(during.y<card.y-10,'outgoing card moves continuously upward');
 assert.equal(await page.locator('.lh-film-card').getAttribute('aria-label'),'1 / 3','old video remains during motion');
 await page.waitForTimeout(650);
 assert.equal(await page.locator('.lh-film-card').getAttribute('aria-label'),'2 / 3');
 assert.equal(await page.locator('.lh-product-character').count(),0,'character must not remain in product carousel');
 const alpha=await clip.evaluate(v=>{const c=document.createElement('canvas');c.width=100;c.height=56;const x=c.getContext('2d');x.drawImage(v,0,0,100,56);return x.getImageData(0,0,1,1).data[3];});
 assert.equal(alpha,0,'video background must decode transparent');
 await page.screenshot({path:'/tmp/lumiq-film-character.png'});
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.waitForFunction(()=>document.querySelector('.lh-film-character').paused);
 assert.equal(await clip.evaluate(v=>v.currentTime),0);
 await page.locator('.lh-films-section').scrollIntoViewIfNeeded();
 await page.waitForFunction(()=>document.querySelector('.lh-film-character').currentTime>0.5);
 await page.emulateMedia({reducedMotion:'reduce'});
 assert.equal(await clip.evaluate(v=>getComputedStyle(v).display),'none');
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 console.log('PASS: film placement, enlarged card, vertical wheel selection, leave reset, re-entry replay, decoded alpha, reduced motion, mobile width');
} finally {await browser.close();}
