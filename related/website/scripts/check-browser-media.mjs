import assert from 'node:assert/strict';
import {chromium,webkit,firefox} from '@playwright/test';
import fs from 'node:fs/promises';
const base=process.env.SITE_URL||'http://localhost:4211',engine=process.env.ENGINE||'webkit';
const output=process.env.QA_OUTPUT||'qa/font-responsive-20261008';await fs.mkdir(output,{recursive:true});
const browser=await ({chromium,webkit,firefox}[engine]).launch(engine==='chromium'?{channel:'chrome',headless:true}:{});
const report={engine,viewports:[],media:[],errors:[]};
try {
  let page=await browser.newPage({viewport:{width:1440,height:1000}});
  for(const [width,height] of [[390,844],[768,1024],[1280,720],[1440,1000],[1920,1080],[2435,498],[2560,500],[3440,1440]]) {
    page.on('pageerror',e=>report.errors.push(e.message));
    await page.setViewportSize({width,height});await page.goto(`${base}/zh-hant?opening=code&background=5`,{waitUntil:'load'});
    if(width>1100)await page.waitForSelector('.lh-opening[data-video-mode]',{state:'attached'});
    else await page.waitForTimeout(600);
    const state=await page.evaluate(()=>({overflow:document.documentElement.scrollWidth>innerWidth+1,legacy:document.querySelectorAll('.lh-glass-word,.lh-hero-object,.lh-brand-character').length,videoMode:document.querySelector('.lh-opening').dataset.videoMode}));
    assert.equal(state.legacy,0);assert.equal(state.overflow,false);
    report.viewports.push({width,height,...state});
    if(width===2435)await page.screenshot({path:`${output}/${engine}-wide.png`});
    page.removeAllListeners('pageerror');await page.close();page=await browser.newPage();
  }
  page.on('pageerror',e=>report.errors.push(e.message));
  await page.setViewportSize({width:1440,height:1000});await page.goto(`${base}/zh-hant`,{waitUntil:'load'});
  await page.waitForFunction(()=>document.querySelector('.lh-opening-video').readyState>=2);
  const movie=page.locator('.lh-opening-video');
  await page.evaluate(()=>scrollTo({top:1100,behavior:'instant'}));
  await page.waitForFunction(()=>{const v=document.querySelector('.lh-opening-video');return !v.seeking&&v.currentTime>1;});
  const forward=await movie.evaluate(v=>v.currentTime);
  await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
  await page.waitForFunction(()=>{const v=document.querySelector('.lh-opening-video');return !v.seeking&&v.currentTime<.05;});
  assert.ok(forward>1);report.media.push({openingForward:forward,reverse:await movie.evaluate(v=>v.currentTime)});
  await page.locator('#films').scrollIntoViewIfNeeded();await page.waitForTimeout(800);
  const film=page.locator('.lh-film-card video');
  await page.locator('.lh-film-toggle').click();
  await page.waitForFunction(()=>{const v=document.querySelector('.lh-film-card video');return !v.paused&&v.currentTime>.15;});
  const first=await film.evaluate(v=>v.currentSrc);
  await page.locator('.lh-films-controls button').last().click();await page.waitForTimeout(1100);
  await page.locator('.lh-film-toggle').click();
  await page.waitForFunction(first=>{const v=document.querySelector('.lh-film-card video');return v.currentSrc!==first&&!v.paused&&v.currentTime>.15;},first);
  report.media.push({first,second:await film.evaluate(v=>v.currentSrc)});
  await page.locator('.lh-films-controls button').last().click();await page.waitForTimeout(1100);
  await page.locator('.lh-film-toggle').click();
  await page.waitForFunction(()=>{const v=document.querySelector('.lh-film-card video');return v.currentSrc.includes('welcome-home')&&!v.paused&&v.currentTime>.15;});
  report.media.push({third:await film.evaluate(v=>v.currentSrc)});
  const background=page.locator('[data-background-video]');
  await page.waitForFunction(()=>document.querySelector('[data-background-video]')?.dataset.ready==='true');
  const cue=await background.evaluate(v=>JSON.parse(v.dataset.scrollCues).find(c=>c[1]===24));
  await page.evaluate(y=>scrollTo({top:y,behavior:'instant'}),cue[0]);
  await page.waitForFunction(()=>{const v=document.querySelector('[data-background-video]');return !v.seeking&&Math.abs(v.currentTime-24)<.15;});
  report.media.push({backgroundAtFamily:await background.evaluate(v=>v.currentTime)});
  await page.emulateMedia({reducedMotion:'reduce'});await page.reload({waitUntil:'load'});
  await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
  await page.waitForSelector('.lh-opening[data-static-opening]',{state:'attached'});
  assert.equal(await movie.getAttribute('src'),null);
  await page.screenshot({path:`${output}/${engine}-reduced.png`});
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.route('**/*.mp4',r=>r.abort());await page.reload({waitUntil:'load'});
  await page.waitForSelector('.lh-opening[data-video-mode]',{state:'attached'});await page.waitForTimeout(800);
  assert.equal(await page.locator('.lh-video-start-poster').evaluate(e=>getComputedStyle(e).visibility),'visible');
  assert.equal(await page.locator('.lh-glass-word,.lh-hero-object').count(),0);
  await page.locator('#films').scrollIntoViewIfNeeded();
  await page.locator('.lh-film-toggle').click();
  await page.waitForSelector('.lh-film-open');
  assert.match(await page.locator('.lh-film-open').getAttribute('href'),/\.mp4$/);
  report.media.push({blockedVideoHasDirectLink:true});
  assert.deepEqual(report.errors,[]);
  console.log(JSON.stringify(report,null,2));
} finally {await browser.close();await fs.writeFile(`${output}/${engine}-media.json`,JSON.stringify(report,null,2));}
