/** Generate the additive editor inventory without rebasing historical seed IDs. */
import {readFile,writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
const require=createRequire(path.join(root,'related/website/package.json'));
const ts=require('typescript'),{parse}=require('@formatjs/icu-messageformat-parser');
const run=(source)=>{const exports={};new Function('exports',ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText)(exports);return exports;};
const {icuSignature}=run(await readFile(path.join(root,'contracts/content-icu.ts'),'utf8'));
const sources=[['faq','brandFaqMessages','BrandFaq','/faq'],['faq','brandStoryFaqMessages','BrandStoryFaq','/faq'],['tablet','brandTabletMessages','BrandTablet','/products/tablet'],['orb','brandOrbMessages','BrandOrb','/products/nest'],['plans','brandPlansMessages','BrandPlans','/plans'],['olago','brandOlaGoMessages','BrandOlaGo','/products/ola-go'],['products','brandProductsMessages','BrandProducts','/products'],['footer','brandFooterMessages','BrandFooter','global/footer']];
const fields=[];
for(const [name,exportName,namespace,page] of sources) {
 const data=run(await readFile(path.join(root,`contracts/brand-${name}.ts`),'utf8'))[exportName];
 const keys=[];
 for(const locale of ['en','zh-hant','ja']) {
  const group=`messages.${locale}.${namespace}`;
  const walk=(value,key)=>{
   const object=value!==null&&typeof value==='object';
   fields.push({path:key,pages:[page],type:object?'object':'string',maxLength:object?null:Math.max(2000,value.length),icuSignature:object?null:icuSignature(parse(value)),mediaPurpose:null,adminOnly:false,editable:!object,owner:'snapshot',optionalGroup:group,...(!object?{initialValue:value}:{})});
   if(object)for(const [child,item] of Object.entries(value))walk(item,`${key}.${child}`);
  };
  walk(data[locale],group);
  keys.push(fields.filter(f=>f.optionalGroup===group).map(f=>f.path.replace(`messages.${locale}.`,'')));
 }
 if(keys.some(paths=>JSON.stringify(paths)!==JSON.stringify(keys[0])))throw Error(`Locale fields differ: ${namespace}`);
}
const output='// Generated by scripts/generate-brand-content-fields.mjs.\nimport type {ContentField,ContentRule} from "./content";\nexport const brandContentFields: readonly (ContentField & {optionalGroup:string})[] = '+JSON.stringify(fields,null,2)+';\nexport const brandContentPolicy: readonly ContentRule[] = brandContentFields;\n';
const destination=path.join(root,'contracts/brand-content-fields.ts');
if(process.argv.includes('--check')){if(await readFile(destination,'utf8')!==output)throw Error('Brand content fields are stale');}
else await writeFile(destination,output);
console.log(`Brand content inventory ${process.argv.includes('--check')?'verified':'generated'}: ${fields.length} additive fields.`);
