/** Keep replacement aliases explicit; historical content and field IDs stay intact. */
import {readFile, writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(path.join(root, 'related/website/package.json'));
const ts = require('typescript');
const run = source => {
  const exports = {};
  new Function('exports', ts.transpileModule(source, {compilerOptions: {module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020}}).outputText)(exports);
  return exports;
};
const seed = JSON.parse(await readFile(path.join(root, 'related/website/lib/content/initial-snapshot.json'), 'utf8'));
const {brandRevisionPatch} = run(await readFile(path.join(root, 'contracts/brand-revision-patch.ts'), 'utf8'));
const approved = new Map(brandRevisionPatch.map(entry => [entry.path, entry]));
const definitions = [
  ['faq', 'brandFaqMessages', 'BrandFaq'],
  ['tablet', 'brandTabletMessages', 'BrandTablet'],
  ['orb', 'brandOrbMessages', 'BrandOrb'],
];
const defaults = {};
for (const [name, exportName, namespace] of definitions) {
  defaults[namespace] = run(await readFile(path.join(root, `contracts/brand-${name}.ts`), 'utf8'))[exportName];
}

const aliases = [];
const alias = (from, to) => aliases.push([from, to]);
for (let number = 1; number <= 6; number++) {
  for (const kind of ['q', 'a']) alias(`Faq.${kind}${number}`, `BrandFaq.${kind}${number}`);
}
alias('Tablet.lede', 'BrandTablet.hero.body');
for (const [from, to] of [['waysTitle', 'title'], ['spotlights', 'eyebrow'], ['spotlightsBody', 'body']]) {
  alias(`Tablet.${from}`, `BrandTablet.stories.${to}`);
}
for (let number = 1; number <= 4; number++) {
  for (const [from, to] of [['Pill', 'Eyebrow'], ['Title', 'Title'], ['Body', 'Body']]) {
    alias(`Tablet.way${number}${from}`, `BrandTablet.stories.story${number}${to}`);
  }
}
for (const [from, to] of [['parents', 'eyebrow'], ['parentsTitle', 'title'], ['parentsBody', 'body']]) {
  alias(`Tablet.${from}`, `BrandTablet.parents.${to}`);
}
for (let number = 1; number <= 5; number++) {
  for (const kind of ['Title', 'Body']) alias(`Tablet.parent${number}${kind}`, `BrandTablet.parents.item${number}${kind}`);
}
for (const [from, to] of [['all', 'allProducts'], ['lede', 'hero.body'], ['waitlist', 'waitlist']]) {
  alias(`Nest.${from}`, `BrandOrb.${to}`);
}
for (const finish of ['oak', 'walnut', 'black']) {
  for (const suffix of ['', 'Note']) alias(`Nest.${finish}${suffix}`, `BrandOrb.finishes.${finish}${suffix}`);
}

const get = (object, path) => path.split('.').reduce((value, key) => value && typeof value === 'object' ? value[key] : undefined, object);
const replacements = [];
for (const locale of ['en', 'zh-hant', 'ja']) {
  for (const [from, to] of aliases) {
    const pathFrom = `messages.${locale}.${from}`;
    const pathTo = `messages.${locale}.${to}`;
    const original = get(seed, pathFrom);
    const [namespace, ...parts] = to.split('.');
    if (typeof original !== 'string' || typeof get(defaults[namespace][locale], parts.join('.')) !== 'string') throw Error(`Invalid brand replacement: ${pathFrom} → ${pathTo}`);
    const patch = approved.get(pathFrom);
    if (patch && (patch.before !== original || typeof patch.after !== 'string')) throw Error(`Invalid approved legacy value: ${pathFrom}`);
    replacements.push({pathFrom, pathTo, original, ...(patch ? {approvedLegacy: patch.after} : {})});
  }
}

const retiredTabletFields = [...new Set(aliases.filter(([from]) => from.startsWith('Tablet.')).map(([from]) => from.slice('Tablet.'.length)))].sort();
const output = `// Generated by scripts/generate-brand-replacements.mjs. Do not edit.
export type BrandContentReplacement = {pathFrom: string; pathTo: string; original: string; approvedLegacy?: string};
/** Clear semantic replacements only; removed capabilities have no invented aliases. */
export const brandContentReplacements: readonly BrandContentReplacement[] = ${JSON.stringify(replacements, null, 2)};
const retiredTabletFields = new Set<string>(${JSON.stringify(retiredTabletFields, null, 2)});
/** Editor inventory only. Validation and stored historical snapshots keep every field. */
export function isActiveBrandContentField(path: string): boolean {
  if (/^messages\\.[^.]+\\.Nest(?:\\.|$)/.test(path)) return false;
  if (/^messages\\.[^.]+\\.Faq\\.[qa][1-6]$/.test(path)) return false;
  const tablet = /^messages\\.[^.]+\\.Tablet\\.([^.]+)$/.exec(path)?.[1];
  if (tablet && (retiredTabletFields.has(tablet) || /^(?:power.*|way5(?:Pill|Title|Body)|titleBefore|titleEm)$/.test(tablet))) return false;
  if (/^plans\\.0\\.rows\\.(?:6|7)(?:\\.|$)/.test(path)) return false;
  if (/^plans\\.1\\.tiers\\.(?:1|3)$/.test(path)) return false;
  if (/^plans\\.1\\.rows\\.[3-6](?:\\.|$)/.test(path)) return false;
  if (/^plans\\.1\\.rows\\.\\d+\\.values\\.(?:1|3)$/.test(path)) return false;
  return true;
}
`;
const destination = path.join(root, 'contracts/brand-replacements.ts');
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== output) throw Error('Brand replacements are stale');
} else await writeFile(destination, output);
console.log(`Brand replacements ${process.argv.includes('--check') ? 'verified' : 'generated'}: ${replacements.length} explicit aliases.`);
